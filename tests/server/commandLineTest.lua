local t = require("tests/testRunner")
local commandLine = require("vracerMP/commands/commandLine")

t.test("options take every word up to the next option; names ignore case", function()
  local command = commandLine.parse("CREATE --Track Circuito Bronco --LAPS 3 --players Ana, Bob")
  t.assertEquals(command.name, "create")
  t.assertEquals(command.options.track, "Circuito Bronco")
  t.assertEquals(command.options.laps, "3")
  t.assertEquals(command.options.players, "Ana, Bob")
  t.assertEquals(#command.arguments, 0)
end)

t.test("words before the first option are arguments", function()
  local command = commandLine.parse("add r-2 --players Ana")
  t.assertEquals(command.arguments[1], "r-2")
  t.assertEquals(command.options.players, "Ana")
end)

t.test("empty text and a bare -- are errors", function()
  t.assertNil(commandLine.parse("   "))
  local command, parseError = commandLine.parse("set -- 3")
  t.assertNil(command)
  t.assertContains(parseError, "missing its name")
end)

t.test("lists are split on commas and trimmed", function()
  local names = commandLine.splitList(" Ana ,Bob,, Carl Jr ")
  t.assertEquals(#names, 3)
  t.assertEquals(names[3], "Carl Jr")
end)

t.test("whole numbers only", function()
  t.assertEquals(commandLine.readWholeNumber("0", "dnf"), 0)
  local number, readError = commandLine.readWholeNumber("2.5", "laps")
  t.assertNil(number)
  t.assertContains(readError, "--laps")
end)

return t.runAll("commandLine")
